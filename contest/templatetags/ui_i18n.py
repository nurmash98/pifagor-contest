@register.filter
def example_newlines(value):
    """В старых примерах задач перенос строки записан текстом "\\n" — показываем как перенос."""
    return (value or '').replace('\\n', '\n')


@register.simple_tag(takes_context=True)
def t(context, text):
    """Переводит text на казахский, если в шапке сайта выбран язык KZ.
    Для русского языка (по умолчанию) или строки без перевода — возвращает
    исходный текст без изменений."""
    lang = context.get('content_lang', 'ru') if hasattr(context, 'get') else 'ru'
    if lang == 'kk':
        return UI_TRANSLATIONS.get(text, text)
    return text


