@register.simple_tag(takes_context=True)
def error_hint(context, error):
    """Простое объяснение ошибки Python (последняя строка stderr) на языке интерфейса."""
    name = (error or '').split(':', 1)[0].strip()
    pair = ERROR_HINTS.get(name)
    if not pair:
        return ''
    lang = context.get('content_lang', 'ru') if hasattr(context, 'get') else 'ru'
    return pair[1] if lang == 'kk' else pair[0]
