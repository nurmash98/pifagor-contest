def J(*rows):
    return "\n".join(" ".join(map(str, r)) if isinstance(r, (list, tuple)) else str(r) for r in rows)


def T(statement, inp, out, note=""):
    """Условие = текст + «Входные данные» + «Выходные данные» (+ примечание)."""
    s = statement.strip() + "\n\nВходные данные\n" + inp.strip() + "\n\nВыходные данные\n" + out.strip()
    if note:
        s += "\n\nПримечание\n" + note.strip()
    return s


