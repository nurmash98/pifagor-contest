def g_rest(R):
    res = []
    def mk(n, m, xm, maxlen):
        W = []
        for _ in range(n):
            l = R.randint(1, m); W.append([l, min(m, l + R.randint(0, maxlen)), R.randint(1, xm)])
        sk = R.randrange(n)
        if R.random() < 0.5 and n > 1:      # спрятать двойника
            W[R.randrange(n)] = list(W[sk])
        diff = [0] * (m + 2)
        for i, (l, r, x) in enumerate(W):
            if i != sk:
                diff[l] += x; diff[r + 1] -= x
        a, cur = [], 0
        for i in range(1, m + 1):
            cur += diff[i]; a.append(cur)
        return J([n, m], *W, a)
    for n, m, xm, ml in [(1, 1, 5, 0), (100, 100, 3, 10), (3000, 3000, 1000, 3000), (3000, 50, 2, 3),
                         (3000, 3000, 1, 0), (20000, 20000, 1000, 1000), (20000, 20000, 2, 5),
                         (20000, 1000, 1, 1000), (20000, 20000, 1000, 20000)]:
        res.append(mk(n, m, xm, ml))
    return res


